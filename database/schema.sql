-- MB Solar PostgreSQL schema
-- Create the database separately, then run this file against it:
--   createdb -U postgres mb_solar
--   psql -U postgres -d mb_solar -v ON_ERROR_STOP=1 -f database/schema.sql

BEGIN;

CREATE TABLE IF NOT EXISTS categories (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_id       BIGINT REFERENCES categories(id) ON DELETE RESTRICT,
    name            TEXT NOT NULL,
    slug            TEXT NOT NULL UNIQUE,
    filter_key      TEXT,
    description     TEXT,
    sort_order      INTEGER NOT NULL DEFAULT 0,
    is_active       BOOLEAN NOT NULL DEFAULT TRUE,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT categories_name_not_blank CHECK (BTRIM(name) <> ''),
    CONSTRAINT categories_slug_not_blank CHECK (BTRIM(slug) <> ''),
    CONSTRAINT categories_not_own_parent CHECK (parent_id IS NULL OR parent_id <> id)
);

CREATE INDEX IF NOT EXISTS categories_parent_sort_idx
    ON categories (parent_id, sort_order, name);

CREATE TABLE IF NOT EXISTS brands (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            TEXT NOT NULL UNIQUE,
    is_active       BOOLEAN NOT NULL DEFAULT TRUE,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT brands_name_not_blank CHECK (BTRIM(name) <> '')
);

CREATE TABLE IF NOT EXISTS partners (
    id              INTEGER PRIMARY KEY,
    name            TEXT NOT NULL UNIQUE,
    logo            TEXT NOT NULL,
    image           TEXT NOT NULL,
    website         TEXT,
    description     TEXT NOT NULL,
    intro_title     TEXT NOT NULL,
    intro_text      TEXT NOT NULL,
    sort_order      INTEGER NOT NULL UNIQUE CHECK (sort_order >= 0),
    CONSTRAINT partners_name_not_blank CHECK (BTRIM(name) <> ''),
    CONSTRAINT partners_logo_not_blank CHECK (BTRIM(logo) <> ''),
    CONSTRAINT partners_image_not_blank CHECK (BTRIM(image) <> '')
);

CREATE TABLE IF NOT EXISTS partner_profiles (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    brand_id        BIGINT NOT NULL UNIQUE REFERENCES brands(id) ON DELETE RESTRICT,
    description     TEXT NOT NULL,
    intro_title     TEXT NOT NULL,
    intro_text      TEXT NOT NULL,
    sort_order      INTEGER NOT NULL DEFAULT 0,
    is_published    BOOLEAN NOT NULL DEFAULT TRUE,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT partner_description_not_blank CHECK (BTRIM(description) <> ''),
    CONSTRAINT partner_intro_title_not_blank CHECK (BTRIM(intro_title) <> '')
);

CREATE TABLE IF NOT EXISTS products (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    brand_id        BIGINT NOT NULL REFERENCES brands(id) ON DELETE RESTRICT,
    category_id     BIGINT NOT NULL REFERENCES categories(id) ON DELETE RESTRICT,
    slug            TEXT NOT NULL UNIQUE,
    name            TEXT NOT NULL,
    model_number    TEXT,
    description     TEXT NOT NULL,
    badge           TEXT,
    is_new          BOOLEAN NOT NULL DEFAULT FALSE,
    is_best_seller  BOOLEAN NOT NULL DEFAULT FALSE,
    is_active       BOOLEAN NOT NULL DEFAULT TRUE,
    sort_order      INTEGER NOT NULL DEFAULT 0,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT products_name_not_blank CHECK (BTRIM(name) <> ''),
    CONSTRAINT products_slug_not_blank CHECK (BTRIM(slug) <> ''),
    CONSTRAINT products_model_number_not_blank CHECK (model_number IS NULL OR BTRIM(model_number) <> ''),
    CONSTRAINT products_description_not_blank CHECK (BTRIM(description) <> '')
);

CREATE INDEX IF NOT EXISTS products_category_active_sort_idx
    ON products (category_id, is_active, sort_order, name);
CREATE INDEX IF NOT EXISTS products_brand_active_sort_idx
    ON products (brand_id, is_active, sort_order, name);
CREATE INDEX IF NOT EXISTS products_newest_idx
    ON products (created_at DESC, sort_order, name) WHERE is_active;
CREATE INDEX IF NOT EXISTS products_best_seller_sort_idx
    ON products (sort_order, name) WHERE is_active AND is_best_seller;

CREATE TABLE IF NOT EXISTS images (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    path            TEXT NOT NULL UNIQUE,
    alt_text        TEXT,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT images_path_not_blank CHECK (BTRIM(path) <> '')
);

CREATE TABLE IF NOT EXISTS product_images (
    product_id      BIGINT NOT NULL REFERENCES products(id) ON DELETE CASCADE,
    image_id        BIGINT NOT NULL REFERENCES images(id) ON DELETE CASCADE,
    sort_order      INTEGER NOT NULL DEFAULT 0 CHECK (sort_order >= 0),
    is_primary      BOOLEAN NOT NULL DEFAULT FALSE,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (product_id, image_id)
);

CREATE INDEX IF NOT EXISTS product_images_image_idx
    ON product_images (image_id, product_id);
CREATE UNIQUE INDEX IF NOT EXISTS product_images_one_primary_per_product_idx
    ON product_images (product_id) WHERE is_primary;

CREATE TABLE IF NOT EXISTS construction_projects (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title           TEXT NOT NULL,
    introduction    TEXT NOT NULL,
    content         TEXT NOT NULL,
    sort_order      INTEGER NOT NULL DEFAULT 0,
    is_published    BOOLEAN NOT NULL DEFAULT TRUE,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT construction_title_not_blank CHECK (BTRIM(title) <> ''),
    CONSTRAINT construction_introduction_not_blank CHECK (BTRIM(introduction) <> ''),
    CONSTRAINT construction_content_not_blank CHECK (BTRIM(content) <> '')
);

CREATE INDEX IF NOT EXISTS construction_projects_published_sort_idx
    ON construction_projects (is_published, sort_order, id);

-- A project can have multiple images; image records can be reused if needed.
CREATE TABLE IF NOT EXISTS construction_project_images (
    project_id      BIGINT NOT NULL REFERENCES construction_projects(id) ON DELETE CASCADE,
    image_id        BIGINT NOT NULL REFERENCES images(id) ON DELETE CASCADE,
    sort_order      INTEGER NOT NULL DEFAULT 0 CHECK (sort_order >= 0),
    is_primary      BOOLEAN NOT NULL DEFAULT FALSE,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (project_id, image_id)
);

CREATE INDEX IF NOT EXISTS construction_project_images_image_idx
    ON construction_project_images (image_id, project_id);
CREATE UNIQUE INDEX IF NOT EXISTS construction_project_images_one_primary_idx
    ON construction_project_images (project_id) WHERE is_primary;

CREATE TABLE IF NOT EXISTS solutions (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title           TEXT NOT NULL,
    introduction    TEXT NOT NULL,
    content         TEXT NOT NULL,
    sort_order      INTEGER NOT NULL DEFAULT 0,
    is_published    BOOLEAN NOT NULL DEFAULT TRUE,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT solutions_title_not_blank CHECK (BTRIM(title) <> ''),
    CONSTRAINT solutions_introduction_not_blank CHECK (BTRIM(introduction) <> ''),
    CONSTRAINT solutions_content_not_blank CHECK (BTRIM(content) <> '')
);

CREATE INDEX IF NOT EXISTS solutions_published_sort_idx
    ON solutions (is_published, sort_order, id);

CREATE TABLE IF NOT EXISTS solution_images (
    solution_id     BIGINT NOT NULL REFERENCES solutions(id) ON DELETE CASCADE,
    image_id        BIGINT NOT NULL REFERENCES images(id) ON DELETE CASCADE,
    sort_order      INTEGER NOT NULL DEFAULT 0 CHECK (sort_order >= 0),
    is_primary      BOOLEAN NOT NULL DEFAULT FALSE,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (solution_id, image_id)
);

CREATE INDEX IF NOT EXISTS solution_images_image_idx
    ON solution_images (image_id, solution_id);
CREATE UNIQUE INDEX IF NOT EXISTS solution_images_one_primary_idx
    ON solution_images (solution_id) WHERE is_primary;

-- Keep updated_at current whenever a row is changed.
CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.updated_at = NOW();
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS categories_set_updated_at ON categories;
CREATE TRIGGER categories_set_updated_at BEFORE UPDATE ON categories
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();
DROP TRIGGER IF EXISTS brands_set_updated_at ON brands;
CREATE TRIGGER brands_set_updated_at BEFORE UPDATE ON brands
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();
DROP TRIGGER IF EXISTS partner_profiles_set_updated_at ON partner_profiles;
CREATE TRIGGER partner_profiles_set_updated_at BEFORE UPDATE ON partner_profiles
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();
DROP TRIGGER IF EXISTS products_set_updated_at ON products;
CREATE TRIGGER products_set_updated_at BEFORE UPDATE ON products
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();
DROP TRIGGER IF EXISTS construction_projects_set_updated_at ON construction_projects;
CREATE TRIGGER construction_projects_set_updated_at BEFORE UPDATE ON construction_projects
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();
DROP TRIGGER IF EXISTS solutions_set_updated_at ON solutions;
CREATE TRIGGER solutions_set_updated_at BEFORE UPDATE ON solutions
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();
DROP TRIGGER IF EXISTS quote_requests_set_updated_at ON quote_requests;
CREATE TRIGGER quote_requests_set_updated_at BEFORE UPDATE ON quote_requests
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

COMMIT;
