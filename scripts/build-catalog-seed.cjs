// Regenerate after editing the six reviewed SQL seeds. No database connection is used.
const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const files = [
  'seed_inverter_categories.sql',
  'seed_solax.sql',
  'seed_solis_sungrow.sql',
  'seed_storage_batteries.sql',
  'seed_inverter_product_images.sql',
  'seed_solutions.sql',
];
const bodies = files.map((name) => {
  const source = fs.readFileSync(path.join(root, 'database', name), 'utf8')
    .replace(/^\uFEFF/, '').replace(/\r\n/g, '\n');
  if (/^\s*(?:DELETE\s+FROM|TRUNCATE|DROP|ALTER|COPY|\\)/mi.test(source)) {
    throw new Error(`Review unexpected operation in ${name} before embedding it.`);
  }
  // Only remove top-level transaction lines, preserving DO $$ BEGIN ... END $$.
  return `-- SOURCE: ${name}\n${source.replace(/^BEGIN;\s*$/gm, '').replace(/^COMMIT;\s*$/gm, '').trim()}\n`;
});
const sql = bodies.join('\n');
const productSlugs = [...new Set([...sql.matchAll(/INSERT INTO products[^;]+?VALUES\s*\(\(SELECT[^;]+?\),\s*\(SELECT[^;]+?\),\s*'([^']+)'/g)].map((m) => m[1]))];
const imageLinks = [...sql.matchAll(/\('(\/image\/[^']+)',\s*'([^']+)',\s*\d+,\s*(?:TRUE|FALSE)\)/g)]
  .map((m) => ({ path: m[1], slug: m[2] }));
if (productSlugs.length !== 50 || imageLinks.length !== 106) {
  throw new Error('Seed manifest changed. Review expected product/image totals before updating it.');
}
const solutionTitles = [
  'Giải pháp điện mặt trời cho hộ gia đình',
  'Giải pháp điện mặt trời cho doanh nghiệp',
  'Giải pháp điện mặt trời kết hợp lưu trữ',
];
const escaped = sql.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${');
const generated = `// Generated by node scripts/build-catalog-seed.cjs from the six reviewed SQL files.
// The route owns the transaction. Requests cannot supply SQL or choose source files.
export const catalogProductSlugs: string[] = ${JSON.stringify(productSlugs, null, 2)};
export const catalogImageLinks: { path: string; slug: string }[] = ${JSON.stringify(imageLinks, null, 2)};
export const catalogSolutionTitles: string[] = ${JSON.stringify(solutionTitles, null, 2)};
export const catalogSeedSql = \`${escaped}\`;
`;
fs.writeFileSync(path.join(root, 'app/api/internal/db-setup/seed-catalog.ts'), generated, 'utf8');
console.log(`Embedded ${files.length} files: ${productSlugs.length} products, ${imageLinks.length} image links, ${solutionTitles.length} solutions.`);
